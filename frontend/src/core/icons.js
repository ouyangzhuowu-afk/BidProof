const isDev = import.meta.env?.DEV ?? false;
const RENDERED = 'data-icon-rendered';

/**
 * 把一个图标名渲染成 SVG 字符串。名字来自受控常量表，不接受外部输入。
 * @param {string} name
 * @param {number} [size]
 */
export function iconSvg(name, size = 16) {
  const body = ICONS[name];
  if (!body) {
    if (isDev) console.warn(`[icons] 未登记的图标：${name}`);
    return `<svg ${SVG_ATTRS} width="${size}" height="${size}" aria-hidden="true"><rect x="4" y="4" width="16" height="16" rx="2"/></svg>`;
  }
  return `<svg ${SVG_ATTRS} width="${size}" height="${size}" aria-hidden="true">${body}</svg>`;
}

/**
 * 在给定子树内渲染尚未渲染的图标占位符。
 * @param {ParentNode} [root] 默认整个文档，但业务代码应当传入刚插入的节点
 */
export function renderIcons(root = document) {
  const targets = root.querySelectorAll(`[data-lucide]:not([${RENDERED}])`);
  for (const node of targets) {
    const name = node.getAttribute('data-lucide');
    if (!name) continue;
    const size = Number(node.getAttribute('data-icon-size')) || 16;
    node.innerHTML = iconSvg(name, size);
    node.setAttribute(RENDERED, '');
    node.setAttribute('aria-hidden', 'true');
  }
}
